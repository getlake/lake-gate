#!/usr/bin/env node
// Regenerates src/meter-core.js from a lake-meter checkout so both tools share one estimator and price table.
// Usage: node scripts/sync-meter.mjs ../exp-a-meter
import fs from 'node:fs';
import path from 'node:path';
const meter = path.resolve(process.argv[2] || '../exp-a-meter', 'src');
const plan = fs.readFileSync(path.join(meter, 'plan.js'), 'utf8').split("import { costOfBudget } from './pricing.js';")[1];
const pricing = 'export function normalizeModelId' + fs.readFileSync(path.join(meter, 'pricing.js'), 'utf8').split('export function normalizeModelId')[1];
const prices = JSON.parse(fs.readFileSync(path.join(meter, 'prices.json'), 'utf8'));
const out = `// GENERATED by scripts/sync-meter.mjs from lake-meter (src/plan.js, src/pricing.js, src/prices.json).
// One estimator for every Lake tool: the same plan gets the same steps, complexity (1-5), model picks and prices
// in lake-gate and lake-meter. Do not edit by hand; run \`node scripts/sync-meter.mjs <path-to-lake-meter>\`.
// Browser-safe: no Node imports.
export const PRICES = ${JSON.stringify(prices, null, 1)};
${plan}
${pricing}`;
fs.writeFileSync(new URL('../src/meter-core.js', import.meta.url), out);
console.log('src/meter-core.js updated from', meter);
